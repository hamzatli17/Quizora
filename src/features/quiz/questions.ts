export const CATEGORY_IDS = [
  'general',
  'geography',
  'science',
  'logic',
] as const;

export type CategoryId = (typeof CATEGORY_IDS)[number];

export type QuizQuestion = {
  id: string;
  categoryId: string;
  question: {
    fr: string;
    en: string;
  };
  answers: {
    id: string;
    text: {
      fr: string;
      en: string;
    };
  }[];
  correctAnswerId: string;
  explanation?: {
    fr: string;
    en: string;
  };
};

type AnswerSeed = { id: string; fr: string; en: string };

function q(
  id: string,
  categoryId: CategoryId,
  fr: string,
  en: string,
  correctAnswerId: string,
  answers: AnswerSeed[],
  explanationFr: string,
  explanationEn: string,
): QuizQuestion {
  return {
    id,
    categoryId,
    question: { fr, en },
    answers: answers.map(answer => ({
      id: answer.id,
      text: { fr: answer.fr, en: answer.en },
    })),
    correctAnswerId,
    explanation: { fr: explanationFr, en: explanationEn },
  };
}

